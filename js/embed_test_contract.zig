//! `zig build test`: writes the test contract's Wasm (js/test_contract.zig) as
//! `const TEST_CONTRACT_WASM = "<base64>";` for js/test.html.
//! Usage: embed_test_contract <contract.wasm> <out.js>
const std = @import("std");

pub fn main(init: std.process.Init) !void {
    const a = init.arena.allocator();
    const args = try init.minimal.args.toSlice(a);
    if (args.len != 3) std.process.fatal("usage: embed_test_contract <contract.wasm> <out.js>", .{});
    const wasm = try std.Io.Dir.cwd().readFileAlloc(init.io, args[1], a, .limited(16 << 20));
    const b64 = try a.alloc(u8, std.base64.standard.Encoder.calcSize(wasm.len));
    _ = std.base64.standard.Encoder.encode(b64, wasm);
    const js = try std.fmt.allocPrint(a,
        \\// Generated by `zig build test` from js/test_contract.zig: the contract js/test.html's follow tests run.
        \\const TEST_CONTRACT_WASM = "{s}";
        \\
    , .{b64});
    try std.Io.Dir.cwd().writeFile(init.io, .{ .sub_path = args[2], .data = js });
}
